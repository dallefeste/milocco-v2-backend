-- Segnalazioni degli utenti (problemi o richieste sul gestionale)
CREATE TABLE support_ticket (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         text,
  user_id      integer REFERENCES app_user(id),
  subject      text NOT NULL,
  priority     text NOT NULL DEFAULT 'MEDIUM' CHECK (priority IN ('LOW', 'MEDIUM', 'HIGH', 'BLOCKING')),
  description  text NOT NULL,
  suggestion   text,
  feedback     text,
  status       text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'TO_VERIFY', 'REJECTED', 'UPDATING', 'RESOLVED', 'NOT_FEASIBLE', 'NOT_REPRODUCIBLE')),
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  deleted_at   timestamptz
);

-- Registro delle modifiche fatte dagli utenti
CREATE TABLE audit_log (
  id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     integer,
  username    text,
  entity      text NOT NULL,
  entity_id   text,
  action      text NOT NULL CHECK (action IN ('CREATE', 'UPDATE', 'DELETE', 'RESTORE', 'ACTION')),
  summary     text,
  changes     jsonb,
  created_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX audit_log_entity_idx ON audit_log (entity, entity_id);
CREATE INDEX audit_log_created_idx ON audit_log (created_at DESC);

