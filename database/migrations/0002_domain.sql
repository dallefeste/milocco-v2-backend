-- Schema di dominio del gestionale di produzione.
-- Convenzioni: id intero, created_at / updated_at, deleted_at = eliminazione logica.
-- Durate in secondi (integer). Importi e quantità decimali in numeric.

-- =========================================================================
-- ANAGRAFICHE
-- =========================================================================

CREATE TABLE customer (
  id                  integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                text NOT NULL,
  -- Identificativo del cliente nel gestionale contabile Onda (anagrafica)
  onda_anagrafica_id  bigint,
  notes               text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  deleted_at          timestamptz
);
CREATE INDEX customer_name_idx ON customer (lower(name));
CREATE UNIQUE INDEX customer_onda_uq ON customer (onda_anagrafica_id) WHERE onda_anagrafica_id IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE supplier (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  notes       text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);

CREATE TABLE department (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  -- Reparto produzione: i suoi operatori usano il tablet e compaiono nei riepiloghi giornalieri
  is_production  boolean NOT NULL DEFAULT false,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);

CREATE TABLE operator (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  first_name     text NOT NULL,
  last_name      text NOT NULL,
  department_id  integer REFERENCES department(id),
  badge_number   text,
  birth_date     date,
  hire_date      date,
  active         boolean NOT NULL DEFAULT true,
  -- PIN facoltativo per identificarsi sul tablet (hash). Vuoto = scelta dall'elenco senza PIN.
  pin_hash       text,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);

CREATE TABLE machine_type (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name                    text NOT NULL,
  -- Fase di taglio barre: il particolare entra nella lista di approvazione taglio
  is_cutting              boolean NOT NULL DEFAULT false,
  -- Fase di collaudo
  is_inspection           boolean NOT NULL DEFAULT false,
  -- Proposta per la pianificazione quando si conferma un ordine cliente
  plan_on_order_confirm   boolean NOT NULL DEFAULT false,
  -- Colonne dell'export Excel del preventivo: quali tempi riportare
  excel_column            text,
  sort_order              integer NOT NULL DEFAULT 100,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  deleted_at              timestamptz
);

CREATE TABLE machine (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name             text NOT NULL,
  machine_type_id  integer NOT NULL REFERENCES machine_type(id),
  hourly_rate      numeric(12,2) NOT NULL DEFAULT 0,
  -- Compare nella pianificazione (code per macchina)
  schedulable      boolean NOT NULL DEFAULT false,
  sort_order       integer NOT NULL DEFAULT 100,
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  deleted_at       timestamptz
);

CREATE TABLE customer_machine_rate (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  machine_id   integer NOT NULL REFERENCES machine(id) ON DELETE CASCADE,
  customer_id  integer NOT NULL REFERENCES customer(id) ON DELETE CASCADE,
  hourly_rate  numeric(12,2) NOT NULL,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (machine_id, customer_id)
);

CREATE TABLE material (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  -- Codice usato nel codice articolo delle barre (es. FE04)
  code          text,
  density       numeric(10,4) NOT NULL DEFAULT 0,   -- g/cm3
  price_per_kg  numeric(12,4) NOT NULL DEFAULT 0,   -- €/kg
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz
);
CREATE INDEX material_code_idx ON material (code);

CREATE TABLE finish (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  code        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);
CREATE UNIQUE INDEX finish_code_uq ON finish (code) WHERE deleted_at IS NULL;

CREATE TABLE treatment (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name           text NOT NULL,
  -- Giorni di attraversamento presso il terzista
  required_days  integer NOT NULL DEFAULT 0,
  unit_price     numeric(12,4),
  unit           text CHECK (unit IN ('KG', 'DM2')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);

CREATE TABLE stop_reason (
  id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name          text NOT NULL,
  description   text,
  kind          text NOT NULL DEFAULT 'INTERRUPTION' CHECK (kind IN ('PAUSE', 'INTERRUPTION')),
  -- Causale di fine giornata: sospende automaticamente la fase
  ends_workday  boolean NOT NULL DEFAULT false,
  sort_order    integer NOT NULL DEFAULT 100,
  created_at    timestamptz NOT NULL DEFAULT now(),
  updated_at    timestamptz NOT NULL DEFAULT now(),
  deleted_at    timestamptz
);

CREATE TABLE extra_activity (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name        text NOT NULL,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);

-- Orario di lavoro dello stabilimento: una riga per giorno della settimana (0 = lunedì … 6 = domenica).
-- Ore vuote = giorno di chiusura.
CREATE TABLE work_calendar_day (
  weekday     smallint PRIMARY KEY CHECK (weekday BETWEEN 0 AND 6),
  start_time  time,
  end_time    time,
  updated_at  timestamptz NOT NULL DEFAULT now(),
  CHECK ((start_time IS NULL AND end_time IS NULL) OR (start_time IS NOT NULL AND end_time IS NOT NULL AND end_time > start_time))
);

-- Giorni di chiusura straordinaria (ferie, festività) esclusi dalla pianificazione.
CREATE TABLE work_calendar_closure (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  day         date NOT NULL UNIQUE,
  reason      text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);

-- Tipologia di barra (materia prima): codice = MP + codice materiale + forma + finitura + dimensioni
CREATE TABLE bar_type (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code         text NOT NULL,
  material_id  integer REFERENCES material(id),
  shape        text NOT NULL,
  finish_id    integer REFERENCES finish(id),
  dimensions   text NOT NULL DEFAULT '',
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  deleted_at   timestamptz
);
CREATE UNIQUE INDEX bar_type_code_uq ON bar_type (code) WHERE deleted_at IS NULL;

-- Giacenza barre in metri lineari per tipologia (copia locale; con Onda attivo viene allineata)
CREATE TABLE bar_stock (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bar_type_id  integer NOT NULL REFERENCES bar_type(id),
  meters       numeric(12,3) NOT NULL DEFAULT 0,
  description  text,
  -- Riga del magazzino Onda (IdDoc/IdRiga) quando la giacenza arriva da lì
  onda_doc_id  bigint,
  onda_row_id  bigint,
  synced_at    timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  UNIQUE (bar_type_id)
);

-- Movimenti di magazzino barre (carico, scarico, rettifica): storico di chi, quando, quanto.
CREATE TABLE bar_stock_movement (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  bar_type_id          integer NOT NULL REFERENCES bar_type(id),
  kind                 text NOT NULL CHECK (kind IN ('LOAD', 'UNLOAD', 'ADJUST')),
  meters               numeric(12,3) NOT NULL,
  meters_after         numeric(12,3),
  reason               text,
  production_order_id  integer,
  operator_id          integer REFERENCES operator(id),
  user_id              integer REFERENCES app_user(id),
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX bar_stock_movement_type_idx ON bar_stock_movement (bar_type_id, created_at DESC);

-- =========================================================================
-- DATI TECNICI: DISEGNI E PARTICOLARI
-- =========================================================================

CREATE TABLE drawing (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  code        text NOT NULL,
  revision    text NOT NULL DEFAULT '',
  name        text NOT NULL DEFAULT '',
  notes       text,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now(),
  deleted_at  timestamptz
);
CREATE INDEX drawing_code_idx ON drawing (lower(code), revision);

CREATE TABLE part (
  id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  internal_code    text NOT NULL,
  name             text NOT NULL DEFAULT '',
  material_id      integer REFERENCES material(id),
  supplier_id      integer REFERENCES supplier(id),
  -- Testo dimensioni grezzo (es. "Barra circolare - d50 L43")
  dimensions       text,
  -- Forma e misure strutturate del calcolatore peso (mm)
  shape            text,
  shape_params     jsonb,
  -- Lunghezza di taglio in mm (parametro L), usata da coda taglio e calcolo barre
  cut_length_mm    numeric(12,2),
  weight_kg        numeric(12,4),
  treatment_dm2    numeric(12,4),
  treatment_kg     numeric(12,4),
  notes            text,
  -- Il pezzo si ricava tagliando una barra
  bar_cut          boolean NOT NULL DEFAULT false,
  bar_type_id      integer REFERENCES bar_type(id),
  created_at       timestamptz NOT NULL DEFAULT now(),
  updated_at       timestamptz NOT NULL DEFAULT now(),
  deleted_at       timestamptz
);
CREATE INDEX part_code_idx ON part (lower(internal_code));

CREATE TABLE drawing_part (
  id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  drawing_id  integer NOT NULL REFERENCES drawing(id) ON DELETE CASCADE,
  part_id     integer NOT NULL REFERENCES part(id),
  quantity    integer NOT NULL DEFAULT 1 CHECK (quantity > 0),
  position    integer NOT NULL DEFAULT 1,
  created_at  timestamptz NOT NULL DEFAULT now(),
  updated_at  timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX drawing_part_drawing_idx ON drawing_part (drawing_id);
CREATE INDEX drawing_part_part_idx ON drawing_part (part_id);

CREATE TABLE drawing_treatment (
  drawing_id    integer NOT NULL REFERENCES drawing(id) ON DELETE CASCADE,
  treatment_id  integer NOT NULL REFERENCES treatment(id),
  PRIMARY KEY (drawing_id, treatment_id)
);

-- Ciclo di lavorazione previsto del particolare: sequenza di fasi con tempi standard
CREATE TABLE part_cycle_step (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  part_id              integer NOT NULL REFERENCES part(id) ON DELETE CASCADE,
  machine_type_id      integer NOT NULL REFERENCES machine_type(id),
  sequence             integer NOT NULL DEFAULT 1,
  setup_seconds        integer NOT NULL DEFAULT 0,
  unit_seconds         integer NOT NULL DEFAULT 0,
  planned_man_minutes  integer,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX part_cycle_step_part_idx ON part_cycle_step (part_id, sequence);

-- =========================================================================
-- COMMERCIALE: PREVENTIVI E ORDINI CLIENTE
-- =========================================================================

CREATE TABLE file_attachment (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  owner_user_id  integer REFERENCES app_user(id),
  original_name  text NOT NULL,
  stored_name    text NOT NULL,
  mime_type      text,
  size_bytes     bigint,
  description    text,
  -- A cosa è collegato (es. 'quote', 'drawing') e id dell'elemento
  entity         text,
  entity_id      integer,
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now(),
  deleted_at     timestamptz
);
CREATE INDEX file_attachment_entity_idx ON file_attachment (entity, entity_id);

CREATE TABLE customer_order (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  -- Codice/numero dell'ordine cliente (per gli importati: numero documento Onda)
  code         text NOT NULL,
  customer_id  integer NOT NULL REFERENCES customer(id),
  order_date   timestamptz NOT NULL DEFAULT now(),
  notes        text,
  -- Documento Onda di provenienza
  onda_doc_id  bigint,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now(),
  deleted_at   timestamptz
);
CREATE INDEX customer_order_customer_idx ON customer_order (customer_id);
CREATE INDEX customer_order_code_idx ON customer_order (code);
CREATE UNIQUE INDEX customer_order_onda_uq ON customer_order (onda_doc_id) WHERE onda_doc_id IS NOT NULL AND deleted_at IS NULL;

CREATE TABLE customer_order_line (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_order_id  integer NOT NULL REFERENCES customer_order(id) ON DELETE CASCADE,
  drawing_id         integer NOT NULL REFERENCES drawing(id),
  quantity           integer NOT NULL CHECK (quantity >= 0),
  status             text NOT NULL DEFAULT 'PENDING' CHECK (status IN ('PENDING', 'CONFIRMED')),
  notes              text,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz
);
CREATE INDEX customer_order_line_order_idx ON customer_order_line (customer_order_id);

CREATE TABLE quote (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  number                  text NOT NULL,
  customer_id             integer NOT NULL REFERENCES customer(id),
  issue_date              date NOT NULL DEFAULT current_date,
  expected_delivery_date  date,
  -- Moltiplicatore del solo costo materiale
  material_markup         numeric(8,4) NOT NULL DEFAULT 1.15,
  -- Moltiplicatore finale
  markup                  numeric(8,4) NOT NULL DEFAULT 1.25,
  customer_order_id       integer REFERENCES customer_order(id),
  imported_file_id        integer REFERENCES file_attachment(id),
  notes                   text,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  deleted_at              timestamptz
);
CREATE INDEX quote_customer_idx ON quote (customer_id);
CREATE INDEX quote_number_idx ON quote (number);

CREATE TABLE quote_part (
  id                     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_id               integer NOT NULL REFERENCES quote(id) ON DELETE CASCADE,
  part_id                integer NOT NULL REFERENCES part(id),
  quantity               integer NOT NULL DEFAULT 0,
  production_quantity    integer NOT NULL DEFAULT 0,
  cam_seconds            integer NOT NULL DEFAULT 0,
  cam_price_per_minute   numeric(12,4) NOT NULL DEFAULT 0,
  material_price_per_kg  numeric(12,4) NOT NULL DEFAULT 0,
  -- Copia dei dati del particolare al momento del preventivo (i costi non cambiano se cambia il particolare)
  weight_kg              numeric(12,4),
  treatment_kg           numeric(12,4),
  treatment_dm2          numeric(12,4),
  notes                  text,
  sort_order             integer NOT NULL DEFAULT 0,
  created_at             timestamptz NOT NULL DEFAULT now(),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  deleted_at             timestamptz
);
CREATE INDEX quote_part_quote_idx ON quote_part (quote_id);
CREATE INDEX quote_part_part_idx ON quote_part (part_id);

CREATE TABLE quote_part_phase (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_part_id        integer NOT NULL REFERENCES quote_part(id) ON DELETE CASCADE,
  machine_type_id      integer NOT NULL REFERENCES machine_type(id),
  machine_id           integer REFERENCES machine(id),
  sequence             integer NOT NULL DEFAULT 1,
  programming_seconds  integer NOT NULL DEFAULT 0,
  setup_seconds        integer NOT NULL DEFAULT 0,
  unit_seconds         integer NOT NULL DEFAULT 0,
  machine_hourly_rate  numeric(12,2) NOT NULL DEFAULT 0,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX quote_part_phase_qp_idx ON quote_part_phase (quote_part_id);

CREATE TABLE quote_part_treatment (
  id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  quote_part_id  integer NOT NULL REFERENCES quote_part(id) ON DELETE CASCADE,
  treatment_id   integer NOT NULL REFERENCES treatment(id),
  unit_price     numeric(12,4) NOT NULL DEFAULT 0,
  unit           text NOT NULL DEFAULT 'KG' CHECK (unit IN ('KG', 'DM2')),
  created_at     timestamptz NOT NULL DEFAULT now(),
  updated_at     timestamptz NOT NULL DEFAULT now()
);

-- =========================================================================
-- PRODUZIONE
-- =========================================================================

-- Ordine di produzione: produrre `quantity` volte un disegno. L'id è il numero d'ordine mostrato.
CREATE TABLE production_order (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  customer_order_id       integer NOT NULL REFERENCES customer_order(id),
  customer_order_line_id  integer REFERENCES customer_order_line(id),
  drawing_id              integer NOT NULL REFERENCES drawing(id),
  quantity                integer NOT NULL CHECK (quantity >= 0),
  -- Quantità destinata a scorta di magazzino
  stock_quantity          integer NOT NULL DEFAULT 0 CHECK (stock_quantity >= 0),
  expected_delivery_date  date,
  status                  text NOT NULL DEFAULT 'TO_DO' CHECK (status IN ('TO_DO', 'IN_PROGRESS', 'COMPLETED')),
  started_at              timestamptz,
  completed_at            timestamptz,
  notes                   text,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  deleted_at              timestamptz
);
CREATE INDEX production_order_status_idx ON production_order (status) WHERE deleted_at IS NULL;
CREATE INDEX production_order_customer_order_idx ON production_order (customer_order_id);
CREATE INDEX production_order_drawing_idx ON production_order (drawing_id);

CREATE TABLE production_order_treatment (
  production_order_id  integer NOT NULL REFERENCES production_order(id) ON DELETE CASCADE,
  treatment_id         integer NOT NULL REFERENCES treatment(id),
  PRIMARY KEY (production_order_id, treatment_id)
);

-- Particolari dell'ordine (uno per riga della composizione del disegno), con stato di approvazione taglio
CREATE TABLE production_order_part (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  production_order_id  integer NOT NULL REFERENCES production_order(id) ON DELETE CASCADE,
  part_id              integer NOT NULL REFERENCES part(id),
  quantity_per_unit    integer NOT NULL DEFAULT 1,
  -- Stato del taglio: NONE = da approvare (se ha fase di taglio), APPROVED = in coda, IGNORED = escluso
  cut_status           text NOT NULL DEFAULT 'NONE' CHECK (cut_status IN ('NONE', 'APPROVED', 'IGNORED')),
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX production_order_part_order_idx ON production_order_part (production_order_id);

-- Lavorazione pianificata su una macchina (coda per macchina ordinata per position)
CREATE TABLE schedule_item (
  id                      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  production_order_id     integer NOT NULL REFERENCES production_order(id),
  part_id                 integer NOT NULL REFERENCES part(id),
  machine_id              integer NOT NULL REFERENCES machine(id),
  setup_seconds           integer NOT NULL DEFAULT 0,
  unit_seconds            integer NOT NULL DEFAULT 0,
  internal_pause_seconds  integer NOT NULL DEFAULT 0,
  end_pause_seconds       integer NOT NULL DEFAULT 0,
  -- Pezzi da produrre (quantità ordine × quantità del particolare nel disegno)
  quantity                integer NOT NULL DEFAULT 0,
  position                numeric(14,4) NOT NULL DEFAULT 0,
  status                  text NOT NULL DEFAULT 'OPEN' CHECK (status IN ('OPEN', 'IN_PROGRESS', 'DONE')),
  completed_at            timestamptz,
  created_at              timestamptz NOT NULL DEFAULT now(),
  updated_at              timestamptz NOT NULL DEFAULT now(),
  deleted_at              timestamptz
);
CREATE INDEX schedule_item_machine_idx ON schedule_item (machine_id, status, position) WHERE deleted_at IS NULL;
CREATE INDEX schedule_item_order_idx ON schedule_item (production_order_id);

-- Coda di taglio barre (unica, ordinata per position)
CREATE TABLE cut_queue_item (
  id                        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  production_order_id       integer NOT NULL REFERENCES production_order(id),
  production_order_part_id  integer REFERENCES production_order_part(id) ON DELETE SET NULL,
  part_id                   integer NOT NULL REFERENCES part(id),
  position                  numeric(14,4) NOT NULL DEFAULT 0,
  status                    text NOT NULL DEFAULT 'WAITING' CHECK (status IN ('WAITING', 'IN_PROGRESS', 'COMPLETED')),
  started_at                timestamptz,
  completed_at              timestamptz,
  created_at                timestamptz NOT NULL DEFAULT now(),
  updated_at                timestamptz NOT NULL DEFAULT now(),
  deleted_at                timestamptz
);
CREATE INDEX cut_queue_item_status_idx ON cut_queue_item (status, position) WHERE deleted_at IS NULL;

-- =========================================================================
-- REPARTO (registrazioni dal tablet)
-- =========================================================================

-- Fase eseguita: attrezzaggio + lavorazione di un particolare su una macchina da parte di un operatore
CREATE TABLE work_phase (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  production_order_id  integer NOT NULL REFERENCES production_order(id),
  part_id              integer REFERENCES part(id),
  operator_id          integer NOT NULL REFERENCES operator(id),
  machine_id           integer NOT NULL REFERENCES machine(id),
  schedule_item_id     integer REFERENCES schedule_item(id),
  -- Numero progressivo per ordine + particolare; una ripresa mantiene il numero della fase sospesa
  phase_number         integer NOT NULL DEFAULT 1,
  -- Fase sospesa da cui questa riprende
  resumed_from_id      integer REFERENCES work_phase(id),
  status               text NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'SUSPENDED')),
  setup_started_at     timestamptz NOT NULL,
  setup_ended_at       timestamptz,
  work_started_at      timestamptz,
  work_ended_at        timestamptz,
  good_qty             integer,
  scrap_qty            integer,
  -- Tempo medio per pezzo misurato con il cronometro del tablet (secondi)
  avg_unit_seconds     numeric(12,2),
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);
CREATE INDEX work_phase_order_idx ON work_phase (production_order_id, part_id);
CREATE INDEX work_phase_operator_idx ON work_phase (operator_id, setup_started_at);
CREATE INDEX work_phase_machine_idx ON work_phase (machine_id, setup_started_at);
CREATE INDEX work_phase_open_idx ON work_phase (status) WHERE status = 'IN_PROGRESS' AND deleted_at IS NULL;

-- Fermo macchina o pausa operatore durante una fase
CREATE TABLE work_stop (
  id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  work_phase_id   integer NOT NULL REFERENCES work_phase(id),
  stop_reason_id  integer REFERENCES stop_reason(id),
  started_at      timestamptz NOT NULL,
  ended_at        timestamptz,
  -- true = la macchina è ferma; false = pausa dell'operatore con macchina che continua a lavorare
  machine_stopped boolean NOT NULL DEFAULT true,
  created_at      timestamptz NOT NULL DEFAULT now(),
  updated_at      timestamptz NOT NULL DEFAULT now(),
  deleted_at      timestamptz
);
CREATE INDEX work_stop_phase_idx ON work_stop (work_phase_id);

CREATE TABLE extra_activity_log (
  id                 integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id        integer NOT NULL REFERENCES operator(id),
  extra_activity_id  integer NOT NULL REFERENCES extra_activity(id),
  machine_id         integer REFERENCES machine(id),
  started_at         timestamptz NOT NULL,
  ended_at           timestamptz,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now(),
  deleted_at         timestamptz
);
CREATE INDEX extra_activity_log_operator_idx ON extra_activity_log (operator_id, started_at);

-- Collaudo di un ordine di produzione
CREATE TABLE inspection (
  id                   integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  production_order_id  integer NOT NULL REFERENCES production_order(id),
  operator_id          integer NOT NULL REFERENCES operator(id),
  machine_id           integer REFERENCES machine(id),
  started_at           timestamptz NOT NULL,
  ended_at             timestamptz,
  good_qty             integer,
  scrap_qty            integer,
  notes                text,
  created_at           timestamptz NOT NULL DEFAULT now(),
  updated_at           timestamptz NOT NULL DEFAULT now(),
  deleted_at           timestamptz
);
CREATE INDEX inspection_order_idx ON inspection (production_order_id);
CREATE INDEX inspection_operator_idx ON inspection (operator_id, started_at);

-- Accessi degli operatori ai tablet di reparto
CREATE TABLE operator_session (
  id           integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  operator_id  integer NOT NULL REFERENCES operator(id),
  machine_id   integer REFERENCES machine(id),
  started_at   timestamptz NOT NULL DEFAULT now(),
  ended_at     timestamptz,
  created_at   timestamptz NOT NULL DEFAULT now(),
  updated_at   timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX operator_session_operator_idx ON operator_session (operator_id, started_at DESC);

